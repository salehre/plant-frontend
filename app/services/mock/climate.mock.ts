function slugify(value: string) {
  return value
    .toLowerCase()
    .replace(/[’']/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

const englishCityText: Record<
  string,
  Pick<CityClimate, "name" | "province" | "climateType">
> = {};
const usedIds = new Set<string>();

export const mockCities: CityClimate[] = provinces.flatMap((province) =>
  province.cities.map(([faName, enName]) => {
    let id = slugify(enName);
    if (usedIds.has(id)) id = `${id}-${slugify(province.en)}`;
    usedIds.add(id);

    englishCityText[id] = {
      name: enName,
      province: province.en,
      climateType: province.profile,
    };
    return {
      id,
      name: faName,
      province: province.fa,
      avgTemp: [...province.avgTemp] as [number, number],
      humidity: province.humidity,
      climateType: climateTypeFa[province.profile],
      suitablePlantSlugs: [...profilePlants[province.profile]],
      ...overrides[id],
    } satisfies CityClimate;
  }),
);

function localizeCity(city: CityClimate, locale: MockLocale): CityClimate {
  return {
    ...city,
    ...(locale === "en" ? englishCityText[city.id] : undefined),
    avgTemp: [...city.avgTemp],
    suitablePlantSlugs: [...city.suitablePlantSlugs],
  };
}

export function getMockCities(locale: MockLocale = "fa"): CityClimate[] {
  return mockCities.map((city) => localizeCity(city, locale));
}

export function findCityById(
  id: string,
  locale: MockLocale = "fa",
): CityClimate | undefined {
  const city = mockCities.find((c) => c.id === id);
  return city ? localizeCity(city, locale) : undefined;
}
